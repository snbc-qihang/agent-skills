"""Hermes packaging adapter."""

from __future__ import annotations

from pathlib import Path
import re

from ..catalog import Catalog
from ..mcp_server import RuntimeTools
from ..version import platform_version


class HermesAdapter:
    id = "hermes"

    def render_tool_references(self, text: str, catalog: Catalog) -> str:
        prefix = catalog.product.id.replace("-", "_")
        names = {tool["name"] for tool in RuntimeTools(catalog.root).definitions()}
        pattern = r"(?<![A-Za-z0-9_])(" + "|".join(re.escape(name) for name in sorted(names)) + r")(?![A-Za-z0-9_])"
        return re.sub(pattern, lambda match: match[0].replace("engineering_assistant_", prefix + "_", 1), text)

    def write_platform_files(self, package_root: Path, catalog: Catalog) -> list[Path]:
        plugin_yaml = package_root / "plugin.yaml"
        version = platform_version(catalog.version, supports_four_part=False)
        plugin_id = catalog.product.id
        tool_prefix = plugin_id.replace("-", "_")
        provides_tools = "".join(
            f"  - {tool['name'].replace('engineering_assistant_', tool_prefix + '_', 1)}\n" for tool in RuntimeTools(catalog.root).definitions()
        )
        plugin_yaml.write_text(
            f"name: {catalog.product.id}\n"
            f'version: "{version}"\n'
            f'canonical_version: "{catalog.version}"\n'
            f'skill_versions_source: "{catalog.product.id}/catalog/skills/public.json"\n'
            'description: "基于证据的工程原语、受治理流程、状态恢复和人工审批门禁。"\n'
            'author: "sunliming625@gmail.com"\n'
            "kind: standalone\n"
            "provides_tools:\n"
            + provides_tools
            + "provides_hooks:\n"
            "  - post_llm_call\n"
            "platforms:\n"
            "  - linux\n"
            "  - macos\n"
            "  - windows\n",
            encoding="utf-8",
        )
        entrypoint = package_root / "__init__.py"
        entrypoint.write_text(
            '"""Generated Hermes adapter for engineering-assistant."""\n\n'
            "import json\n"
            "import re\n"
            "import hashlib\n"
            "import importlib\n"
            "import importlib.util\n"
            "import os\n"
            "import secrets\n"
            "import sys\n"
            "import threading\n"
            "import time\n"
            "from pathlib import Path\n\n"
            "_ROOT = Path(__file__).resolve().parent\n"
            "_RUNTIME_ROOT = _ROOT / 'teamwork-engineering-assistant' / 'runtime/engineering_assistant'\n"
            "_NAMESPACE = '_ea_runtime_' + hashlib.sha256(str(_ROOT).encode()).hexdigest()[:24]\n"
            "if _NAMESPACE not in sys.modules:\n"
            "    _spec = importlib.util.spec_from_file_location(_NAMESPACE, _RUNTIME_ROOT / '__init__.py', submodule_search_locations=[str(_RUNTIME_ROOT)])\n"
            "    _runtime = importlib.util.module_from_spec(_spec)\n"
            "    _runtime.__plugin_id__ = 'teamwork-engineering-assistant'\n"
            "    sys.modules[_NAMESPACE] = _runtime\n"
            "    try:\n"
            "        _spec.loader.exec_module(_runtime)\n"
            "    except Exception:\n"
            "        for _key in list(sys.modules):\n"
            "            if _key == _NAMESPACE or _key.startswith(_NAMESPACE + '.'):\n"
            "                sys.modules.pop(_key, None)\n"
            "        raise\n"
            "load_catalog = importlib.import_module(_NAMESPACE + '.catalog').load_catalog\n"
            "RuntimeTools = importlib.import_module(_NAMESPACE + '.mcp_server').RuntimeTools\n"
            "try:\n"
            "    FeedbackCollector = importlib.import_module(_NAMESPACE + '.feedback').FeedbackCollector\n"
            "    is_explicit_plugin_request = importlib.import_module(_NAMESPACE + '.hook_gate').is_explicit_plugin_request\n"
            f"    _FEEDBACK = FeedbackCollector(_ROOT / '{catalog.product.id}/schemas')\n"
            "except Exception:\n"
            "    _FEEDBACK = None\n"
            "    def is_explicit_plugin_request(_prompt):\n"
            "        return False\n\n"
            "try:\n"
            "    UsageObservationController = importlib.import_module(_NAMESPACE + '.usage_observation').UsageObservationController\n"
            "    _OBSERVER = UsageObservationController(\n"
            f"        _ROOT / '{catalog.product.id}/schemas',\n"
            "        coverage=('hermes_plugin_tool',),\n"
            "    )\n"
            "except Exception:\n"
            "    _OBSERVER = None\n\n"
            f"_CATALOG = load_catalog(_ROOT / '{catalog.product.id}')\n"
            f"_TOOLS = RuntimeTools(_ROOT / '{catalog.product.id}')\n\n\n"
            "_ACTIVE_TURNS = {}\n"
            "_ACTIVE_TURNS_LOCK = threading.RLock()\n"
            "_MAX_ACTIVE_TURNS = 1024\n\n\n"
            "_ACTIVE_TURN_TTL_SECONDS = 3600\n\n\n"
            "def _turn_key(session_id, kwargs):\n"
            "    activity_id = kwargs.get('task_id') or kwargs.get('turn_id')\n"
            "    if session_id is None or activity_id is None:\n"
            "        return None\n"
            "    return str(session_id), str(activity_id)\n\n\n"
            "def _store_active(key, state, expires_at):\n"
            "    if key is None:\n"
            "        return\n"
            "    with _ACTIVE_TURNS_LOCK:\n"
            "        now = time.monotonic()\n"
            "        expired = [item for item, value in _ACTIVE_TURNS.items() if value[1] < now]\n"
            "        for item in expired:\n"
            "            _ACTIVE_TURNS.pop(item, None)\n"
            "        if key not in _ACTIVE_TURNS and len(_ACTIVE_TURNS) >= _MAX_ACTIVE_TURNS:\n"
            "            oldest = next(iter(_ACTIVE_TURNS), None)\n"
            "            if oldest is not None:\n"
            "                _ACTIVE_TURNS.pop(oldest, None)\n"
            "        _ACTIVE_TURNS[key] = (state, expires_at)\n\n\n"
            "def _activate_turn(session_id, kwargs):\n"
            "    key = _turn_key(session_id, kwargs)\n"
            "    if key is None:\n"
            "        return\n"
            "    _store_active(key, 'tool', time.monotonic() + _ACTIVE_TURN_TTL_SECONDS)\n\n\n"
            "def _observation_context(session_id, kwargs):\n"
            "    key = _turn_key(session_id, kwargs)\n"
            "    cwd = kwargs.get('cwd')\n"
            "    if key is None or cwd is None:\n"
            "        return None\n"
            "    return {'session_id': str(session_id), 'turn_id': key[1], 'cwd': str(cwd)}\n\n\n"
            "def _observe_before(name, args, kwargs):\n"
            "    if _OBSERVER is None:\n"
            "        return None\n"
            "    context = _observation_context(kwargs.get('session_id'), kwargs)\n"
            "    if context is None:\n"
            "        return None\n"
            "    payload = {\n"
            "        **context, 'hook_event_name': 'PreToolUse',\n"
            "        'tool_name': f'mcp__engineering_assistant__{name}',\n"
            "        'tool_input': args, 'tool_use_id': secrets.token_hex(12),\n"
            "    }\n"
            "    _OBSERVER.handle(payload, os.environ)\n"
            "    return payload\n\n\n"
            "def _observe_after(payload, response):\n"
            "    if _OBSERVER is None or payload is None:\n"
            "        return\n"
            "    _OBSERVER.handle(\n"
            "        {**payload, 'hook_event_name': 'PostToolUse', 'tool_response': response},\n"
            "        os.environ,\n"
            "    )\n\n\n"
            f"_TOOL_PREFIX = {tool_prefix!r}\n"
            "_TOOL_NAMES = {tool['name'] for tool in _TOOLS.definitions()}\n"
            "_TOOL_REFERENCE = re.compile(r'(?<![A-Za-z0-9_])(' + '|'.join(re.escape(name) for name in sorted(_TOOL_NAMES)) + r')(?![A-Za-z0-9_])')\n\n"
            "def _host_payload(value, prose=False):\n"
            "    if isinstance(value, dict):\n"
            "        return {key: _host_payload(item, key in {'description', 'reason', 'node_goal', 'completion_criteria', 'condition', 'effect', 'next_action', 'next_actions'}) for key, item in value.items()}\n"
            "    if isinstance(value, list):\n"
            "        return [_host_payload(item, prose) for item in value]\n"
            "    if prose and isinstance(value, str):\n"
            "        return _TOOL_REFERENCE.sub(lambda match: match[0].replace('engineering_assistant_', _TOOL_PREFIX + '_', 1), value)\n"
            "    return value\n\n"
            "def _handler(name):\n"
            "    def invoke(args, **kwargs):\n"
            "        observation = None\n"
            "        try:\n"
            "            _activate_turn(kwargs.get('session_id'), kwargs)\n"
            "            observation = _observe_before(name, args, kwargs)\n"
            "        except Exception:\n"
            "            pass\n"
            "        try:\n"
            "            response = json.dumps(_host_payload(_TOOLS.call(name, args)), ensure_ascii=False)\n"
            "        except Exception:\n"
            "            response = json.dumps({'error': 'ToolExecutionError', 'status': 'failed'}, ensure_ascii=False)\n"
            "            try:\n"
            "                context = _observation_context(kwargs.get('session_id'), kwargs)\n"
            "                if _FEEDBACK is not None and context is not None:\n"
            "                    mode = kwargs.get('feedback_mode') or os.environ.get('ENGINEERING_ASSISTANT_FEEDBACK_MODE', 'candidates')\n"
            "                    _FEEDBACK.collect_tool_result(\n"
            "                        {**context, 'tool_name': f'mcp__engineering_assistant__{name}', 'tool_response': {'error': 'ToolExecutionError', 'status': 'failed'}},\n"
            "                        mode=mode, platform='hermes',\n"
            "                    )\n"
            "            except Exception:\n"
            "                pass\n"
            "        try:\n"
            "            _observe_after(observation, response)\n"
            "        except Exception:\n"
            "            pass\n"
            "        return response\n"
            "    return invoke\n\n\n"
            "def _capture_feedback(session_id, user_message, assistant_response, conversation_history, model, platform, **kwargs):\n"
            "    key = None\n"
            "    try:\n"
            "        if _FEEDBACK is None:\n"
            "            return None\n"
            "        key = _turn_key(session_id, kwargs)\n"
            f"        explicitly_requested = isinstance(user_message, str) and is_explicit_plugin_request(user_message, plugin_id='{catalog.product.id}')\n"
            "        now = time.monotonic()\n"
            "        with _ACTIVE_TURNS_LOCK:\n"
            "            state = _ACTIVE_TURNS.get(key)\n"
            "        tool_active = state is not None and state[0] == 'tool' and state[1] >= now\n"
            "        if not (explicitly_requested or tool_active):\n"
            "            if key is not None:\n"
            "                with _ACTIVE_TURNS_LOCK:\n"
            "                    _ACTIVE_TURNS.pop(key, None)\n"
            "            return None\n"
            "        mode = kwargs.get('feedback_mode') or os.environ.get('ENGINEERING_ASSISTANT_FEEDBACK_MODE', 'candidates')\n"
            "        observation_context = _observation_context(session_id, kwargs)\n"
            "        observation_complete = _OBSERVER is None or observation_context is None or mode != 'candidates'\n"
            "        feedback_complete = False\n"
            "        try:\n"
            "            if _OBSERVER is not None and observation_context is not None:\n"
            "                observation_payload = {**observation_context, 'hook_event_name': 'UserPromptSubmit', 'prompt': user_message}\n"
            "                if explicitly_requested and not _OBSERVER.is_active(observation_payload):\n"
            "                    _OBSERVER.handle(observation_payload, os.environ)\n"
            "                if mode == 'candidates' and _OBSERVER.is_active(observation_payload):\n"
            "                    _FEEDBACK.collect_usage_efficiency(\n"
            "                        project_root=observation_context['cwd'],\n"
            "                        ledger=_OBSERVER.current_ledger(observation_payload),\n"
            "                        source='post_llm_call',\n"
            "                    )\n"
            "                    observation_complete = True\n"
            "        except Exception:\n"
            "            pass\n"
            "        _FEEDBACK.collect_hermes_turn(\n"
            "            project_root=kwargs.get('cwd') or Path.cwd(),\n"
            "            session_id=session_id, turn_id=str(kwargs.get('turn_id') or f'{session_id}:{len(conversation_history)}'),\n"
            "            user_message=user_message, assistant_response=assistant_response,\n"
            "            model=model, platform=platform,\n"
            "            mode=mode,\n"
            "        )\n"
            "        feedback_complete = True\n"
            "        if observation_complete and feedback_complete and _OBSERVER is not None and observation_context is not None:\n"
            "            try:\n"
            "                _OBSERVER.discard_ledger(observation_payload)\n"
            "            except Exception:\n"
            "                pass\n"
            "        if key is not None and observation_complete and feedback_complete:\n"
            "            with _ACTIVE_TURNS_LOCK:\n"
            "                _ACTIVE_TURNS.pop(key, None)\n"
            "    except Exception:\n"
            "        return None\n"
            "    return None\n\n\n"
            "def register(ctx) -> None:\n"
            f"    tool_prefix = {tool_prefix!r}\n"
            "    for tool in _TOOLS.definitions():\n"
            "        host_name = tool['name'].replace('engineering_assistant_', tool_prefix + '_', 1)\n"
            "        schema = {\n"
            "            'name': host_name,\n"
            "            'description': tool['description'],\n"
            "            'parameters': tool['inputSchema'],\n"
            "        }\n"
            "        ctx.register_tool(\n"
            f"            name=host_name, toolset='{catalog.product.id}',\n"
            "            schema=schema, handler=_handler(tool['name']),\n"
            "        )\n"
            "    if _FEEDBACK is not None:\n"
            "        ctx.register_hook('post_llm_call', _capture_feedback)\n"
            "    skills_root = Path(__file__).resolve().parent / 'skills'\n"
            "    for skill_md in sorted(skills_root.glob('*/SKILL.md')):\n"
            "        ctx.register_skill(skill_md.parent.name, skill_md)\n",
            encoding="utf-8",
        )
        return [plugin_yaml, entrypoint]
